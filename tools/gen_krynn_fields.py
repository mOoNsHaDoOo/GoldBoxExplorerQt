#!/usr/bin/env python3
"""Generate src/parse/krynn_fields.cpp from the readable C port of the Amiga
Champions of Krynn executable.

The C port documents every field of the in-memory character, item and effect
records in comments such as ``ch+$11E: experience points (long)`` (and ``A+$``/``B+$``
for the game state blocks saved in savgam*.dat). This script
collects those comments (longest description per offset) and the name tables
that H004 copies into H005 (item name words, races, classes, alignments), so
the explorer can label CoK records without inventing field names.

Usage: tools/gen_krynn_fields.py /path/to/src_c/readable > src/parse/krynn_fields.cpp
"""

import collections
import glob
import os
import re
import sys


def collect_fields(src):
    found = collections.defaultdict(set)
    pattern = re.compile(
        r"\b(ch|item|ogg|eff|A|B|C)\+\$([0-9A-F]+): ([^;*]*?)"
        r"(?=(?:;|\*/| [A-Za-z]+\+\$[0-9A-F]+:|$))")
    for path in sorted(glob.glob(os.path.join(src, "*.c")) + glob.glob(os.path.join(src, "*.h"))):
        with open(path, errors="replace") as handle:
            text = handle.read()
        # Join multi-line comments so descriptions are not cut at line ends.
        text = re.sub(r"\n\s*\*\s*", " ", text)
        for match in pattern.finditer(text):
            kind = "item" if match.group(1) == "ogg" else match.group(1)
            found[(kind, int(match.group(2), 16))].add(match.group(3).strip())
    fields = []
    for (kind, offset), descriptions in found.items():
        best = max(descriptions, key=lambda d: (len(d), d))
        if best.startswith("base -1 of"):
            continue
        if "(long" in best:
            size = 4
        elif "(word" in best or " words" in best or "word)" in best:
            size = 2
        else:
            size = 1
        fields.append((kind, offset, size, best))
    # Strings that the comments describe as ranges.
    fields.append(("ch", 0x00, 15, "name of the character (15 characters, terminated at +$0F)"))
    fields.append(("item", 0x00, 40, "name text (+$00..+$27)"))
    unique = {}
    for kind, offset, size, text in fields:
        key = (kind, offset)
        if key not in unique or size > unique[key][2]:
            unique[key] = (kind, offset, size, text)
    order = {"ch": 0, "item": 1, "eff": 2, "A": 3, "B": 4, "C": 5}
    return sorted(unique.values(), key=lambda f: (order[f[0]], f[1]))


def collect_table(src, base, step, count_hint=None):
    with open(os.path.join(src, "h004_init_data.h")) as handle:
        text = handle.read()
    entries = {}
    for match in re.finditer(r'H004_STR, 0x([0-9A-F]+), (\d+), "((?:[^"\\]|\\.)*)"', text):
        address = int(match.group(1), 16)
        if address >= base and (address - base) % step == 0:
            entries[(address - base) // step] = match.group(3)
    result = []
    index = 0
    while index in entries and (count_hint is None or index < count_hint):
        result.append(entries[index])
        index += 1
    return result


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    fields = collect_fields(src)
    item_words = collect_table(src, 0x406E, 0x16)
    races = collect_table(src, 0x4D04, 0x10, 8)
    classes = collect_table(src, 0x4D84, 0x1C)
    alignments = collect_table(src, 0x4C62, 0x12, 9)

    out = []
    out.append("// Generated by tools/gen_krynn_fields.py from the readable C port of the")
    out.append("// Amiga Champions of Krynn executable. Do not edit by hand.")
    out.append('#include "parse/krynn_fields.h"')
    out.append("")
    out.append("namespace KrynnFields {")
    out.append("")
    out.append("const Field fields[] = {")
    for kind, offset, size, text in fields:
        kind_enum = {"ch": "Character", "item": "Item", "eff": "Effect",
                     "A": "StateA", "B": "StateB", "C": "StateC"}[kind]
        out.append("    {Kind::%s, 0x%03X, %d, %s}," % (kind_enum, offset, size, c_string(text)))
    out.append("};")
    out.append("const int fieldCount = sizeof(fields) / sizeof(fields[0]);")
    out.append("")
    for name, values in (("itemWords", item_words), ("races", races),
                         ("classes", classes), ("alignments", alignments)):
        out.append("const char *const %s[] = {" % name)
        for value in values:
            out.append("    %s," % c_string(value))
        out.append("};")
        out.append("const int %sCount = %d;" % (name, len(values)))
        out.append("")
    out.append("} // namespace KrynnFields")
    print("\n".join(out))


if __name__ == "__main__":
    main()
