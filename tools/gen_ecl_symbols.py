#!/usr/bin/env python3
"""Generates src/parse/ecl_basic_symbols.cpp from the campaign symbols.json.

Usage: gen_ecl_symbols.py SYMBOLS.json OUT.cpp

symbols.json maps "R:XXXX" (region A/B/C/R and the hex address the ECL
operand points to) to {"name": ..., "desc": ...}.  Only the key, the name and
the description are kept.  The generated file is checked in so that the
build does not need Python.
"""
import json
import sys


def c_string(text):
    out = []
    for ch in text:
        if ch in '\\"':
            out.append('\\' + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append('\\x%02x' % ord(ch) if ord(ch) < 0x80 else '?')
    return '"' + ''.join(out) + '"'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    with open(sys.argv[1], encoding='utf-8') as f:
        syms = json.load(f)
    lines = [
        '// Generated by tools/gen_ecl_symbols.py from symbols.json. Do not edit.',
        '#include "parse/ecl_basic_symbols.h"',
        '',
        'namespace {',
        'const EclBasicSymbol kSymbols[] = {',
    ]
    for key in sorted(syms):
        entry = syms[key]
        lines.append('    {%s, %s, %s},' % (c_string(key), c_string(entry['name']),
                                            c_string(entry.get('desc', ''))))
    lines += [
        '};',
        '} // namespace',
        '',
        'const EclBasicSymbol *eclBasicSymbols(int *count)',
        '{',
        '    if (count)',
        '        *count = static_cast<int>(sizeof(kSymbols) / sizeof(kSymbols[0]));',
        '    return kSymbols;',
        '}',
        '',
    ]
    with open(sys.argv[2], 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
